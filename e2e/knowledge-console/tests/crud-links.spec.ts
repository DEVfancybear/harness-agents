import { test, expect } from '../fixture';
import { KnowledgePage } from '../knowledge.page';

test('create/edit/move documents keeps links, graph, hashes and durable content', async ({ page, console: app }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const ui = new KnowledgePage(page);
  await ui.open(app.url);
  await ui.folder('research');
  await ui.create('target.md', '# Target\n\nORBIT-517\n\n| Fact | Value |\n|---|---|\n| Period | 21 |');
  await expect(page.locator('#markdown table')).toBeVisible();
  await ui.create('source.md', '# Source\n\n[Target](target.md)');
  await page.locator('#markdown').getByRole('link', { name: 'Target', exact: true }).click();
  await expect(page.locator('#document-title')).toHaveText('Target');
  await expect(page.locator('#backlinks')).toContainText('source.md');
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'Edit document', exact: true });
  await edit.getByLabel('Markdown', { exact: true }).fill('# Target\n\nORBIT-518 updated');
  await edit.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(edit).toHaveCount(0);
  await expect(page.locator('#markdown')).toContainText('ORBIT-518 updated');
  await page.getByRole('button', { name: 'Move', exact: true }).click();
  const move = page.getByRole('dialog', { name: 'Move document', exact: true });
  await move.getByLabel('Destination folder', { exact: true }).selectOption('research');
  await move.getByRole('button', { name: 'Move', exact: true }).click();
  await expect(move).toHaveCount(0);
  await expect(page.locator('#document-path')).toHaveText('research/target.md');
  const source = await (await app.api.get('/api/page?scope=project&path=source.md')).json();
  expect(source.content).toContain('research/target.md');
  await page.getByRole('tab', { name: 'Graph', exact: true }).click();
  await expect(page.locator('#graph-count')).toHaveText('(2)');
  const graph = await (await app.api.get('/api/graph?scope=project')).json();
  expect(graph.edges).toContainEqual({ source: 'source.md', target: 'research/target.md' });
  const zoom = await page.locator('#zoom-label').innerText();
  await page.getByRole('button', { name: 'Zoom graph in', exact: true }).click();
  await expect(page.locator('#zoom-label')).not.toHaveText(zoom);
  await page.reload();
  await expect(page.locator('#markdown')).toContainText('ORBIT-518 updated');
  await page.screenshot({ path: app.root + '/knowledge.png', fullPage: true });
  expect(errors).toEqual([]);
});
