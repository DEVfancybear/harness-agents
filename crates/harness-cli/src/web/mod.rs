//! The loopback web surface: an authenticated HTTP API over the existing
//! services, plus the static UI that reads it.
//!
//! Three rules shape this module, and each one is a decision rather than a
//! convenience (see `ADR-N10`):
//!
//! 1. **No route writes SQL.** Every mutation goes through `SessionService`, so
//!    ownership, policy and durability stay with their owners.
//! 2. **Loopback is not an authentication boundary.** Another process on the
//!    same machine can reach a loopback port, so every mutation carries a token
//!    the host generated at startup, and every request carries an `Origin` the
//!    allowlist accepts.
//! 3. **The event cursor is the journal sequence**, not a counter of what this
//!    process happens to have buffered. A cursor older than the retained range
//!    is answered with an explicit `gap`, because a client that silently
//!    receives a partial replay believes it is up to date.

